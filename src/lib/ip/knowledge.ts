export function detectIndustry(input: {
  name?: string;
  industry?: string;
  products?: string;
  targetCustomer?: string;
}): IndustryKey {
  const haystack = [input.name, input.industry, input.products, input.targetCustomer]
    .filter(Boolean)
    .join(" ")
    .toLowerCase();
  if (!haystack) return "generic";

  let best: { key: IndustryKey; hits: number } = { key: "generic", hits: 0 };
  KEYWORD_MAP.forEach((entry) => {
    const hits = entry.keywords.reduce((acc, keyword) => (haystack.includes(keyword) ? acc + 1 : acc), 0);
    if (hits > best.hits) best = { key: entry.key, hits };
  });
  return best.hits > 0 ? best.key : "generic";
}

export type IpFillContext = {
  name: string;
  city: string;
  industry: string;
  product: string;
  customer: string;
};

/** 把模板里的 {name} / {city} / {product} / {customer} / {industry} 占位符替换成具体值。 */
export function fillTemplate(template: string, context: IpFillContext): string {
  return template
    .replace(/\{name\}/g, context.name || "这位主理人")
    .replace(/\{city\}/g, context.city || "本地")
    .replace(/\{product\}/g, context.product || context.industry || "你的业务")
    .replace(/\{customer\}/g, context.customer || "目标客户")
    .replace(/\{industry\}/g, context.industry || "这个行业");
}
